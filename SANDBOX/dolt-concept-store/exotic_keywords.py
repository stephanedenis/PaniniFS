def _is_kanji(char):
    """Check if a character is a CJK Unified Ideograph (kanji)."""
    cp = ord(char)
    return (0x4E00 <= cp <= 0x9FFF) or (0x3400 <= cp <= 0x4DBF) or (0xF900 <= cp <= 0xFAFF)


def _extract_kanji_stems(keywords):
    """Extract kanji stem(s) from Japanese dictionary-form keywords.
    
    Japanese verbs/adjectives follow the pattern: kanji + hiragana suffix
    E.g.: 走る → stem=走, 逃げる → stem=逃, 落ちる → stem=落
    
    Returns a set of unique kanji stems not already in the keyword list.
    """
    stems = set()
    existing = set(keywords)
    for kw in keywords:
        if len(kw) >= 2:
            # Extract leading kanji characters
            kanji_prefix = []
            for ch in kw:
                if _is_kanji(ch):
                    kanji_prefix.append(ch)
                else:
                    break
            if kanji_prefix:
                stem = ''.join(kanji_prefix)
                if stem not in existing:
                    stems.add(stem)
    return stems


def merge_exotic_keywords(atom_keywords):
    """Merge EXOTIC_KEYWORDS into the main ATOM_KEYWORDS dictionary.
    
    Called at module load time by gutenberg_multilingual_validator.py.
    Modifies atom_keywords in-place.
    
    For Japanese: also adds kanji stems extracted from dictionary-form keywords
    (e.g., 走る → 走) to improve matching on conjugated forms.
    """
    for atom, lang_dict in EXOTIC_KEYWORDS.items():
        if atom not in atom_keywords:
            continue  # Skip unknown atoms
        for lang, keywords in lang_dict.items():
            if lang not in atom_keywords[atom]:
                atom_keywords[atom][lang] = keywords[:]
            else:
                # Merge, avoiding duplicates
                existing = set(atom_keywords[atom][lang])
                atom_keywords[atom][lang].extend(
                    kw for kw in keywords if kw not in existing
                )
            # v4.3: Add kanji stems for Japanese
            if lang == "ja":
                stems = _extract_kanji_stems(atom_keywords[atom][lang])
                if stems:
                    atom_keywords[atom][lang].extend(stems)


def is_cjk_language(lang):
    """Check if a language code is CJK (Chinese/Japanese/Korean)."""
    return lang in ("zh", "ja", "ko", "zh-tw", "zh-cn")


def is_cjk_char(char):
    """Check if a character is CJK (Chinese/Japanese/Korean).
    
    Covers:
      - CJK Unified Ideographs (4E00-9FFF)
      - CJK Extension A (3400-4DBF)
      - CJK Extension B (20000-2A6DF)
      - CJK Compatibility Ideographs (F900-FAFF)
      - Hiragana (3040-309F)
      - Katakana (30A0-30FF)
      - Hangul Syllables (AC00-D7AF)
    """
    cp = ord(char)
    return (
        (0x4E00 <= cp <= 0x9FFF) or    # CJK Unified Ideographs
        (0x3400 <= cp <= 0x4DBF) or    # CJK Extension A
        (0x20000 <= cp <= 0x2A6DF) or  # CJK Extension B
        (0xF900 <= cp <= 0xFAFF) or    # CJK Compatibility
        (0x3040 <= cp <= 0x309F) or    # Hiragana
        (0x30A0 <= cp <= 0x30FF) or    # Katakana
        (0xAC00 <= cp <= 0xD7AF)       # Hangul
    )


def cjk_tokenize(text, lang, atom_keywords):
    """Tokenize CJK text using keyword-aware greedy matching.
    
    Instead of whitespace splitting, scans text character by character
    and uses a longest-match-first strategy against known keywords.
    
    Returns a list of tokens (strings), where CJK keyword matches are
    preserved as units and other characters form individual tokens.
    """
    # Build keyword set for this language (all atoms combined)
    all_keywords = set()
    for atom, kw_by_lang in atom_keywords.items():
        if lang in kw_by_lang:
            all_keywords.update(kw_by_lang[lang])
    
    # Sort by length descending for greedy matching
    sorted_keywords = sorted(all_keywords, key=len, reverse=True)
    max_kw_len = max((len(kw) for kw in sorted_keywords), default=1)
    
    tokens = []
    i = 0
    text_len = len(text)
    
    while i < text_len:
        char = text[i]
        
        # Skip whitespace and common punctuation
        if char.isspace() or char in '.,;:!?"\'"()[]{}—–-…""''«»。、！？「」『』（）【】《》〈〉・':
            i += 1
            continue
        
        # For non-CJK characters, collect as a word token (handles mixed text)
        if not is_cjk_char(char):
            word = []
            while i < text_len and not text[i].isspace() and not is_cjk_char(text[i]):
                if text[i] not in '.,;:!?"\'"()[]{}—–-…""''«»。、！？':
                    word.append(text[i])
                i += 1
            if word:
                tokens.append(''.join(word))
            continue
        
        # CJK character: try greedy longest match
        matched = False
        for try_len in range(min(max_kw_len, text_len - i), 0, -1):
            substr = text[i:i + try_len]
            if substr in all_keywords:
                tokens.append(substr)
                i += try_len
                matched = True
                break
        
        if not matched:
            # Single CJK character as token
            tokens.append(char)
            i += 1
    
    return tokens
